function mdl = ml_train_ECOC(X, Y, params, varargin)

    tSVM = templateSVM( ...
        'KernelFunction', 'rbf', ...
        'Standardize',    true, ...
        'KernelScale',    params.sigmas, ...
        'BoxConstraint',  params.boxconstr, ...
        'Type',           'classification');

    baseArgs = { ...
        'Learners', tSVM, ...
        'Coding',   'onevsone'};

    mdl = fitcecoc(X, Y, baseArgs{:}, varargin{:});
end
